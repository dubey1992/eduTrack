# A URL matching no route above never reaches DRF, so it would answer Django's
# HTML page - which the Flutter client reads as a parse failure rather than as
# a 404. These keep the error envelope true for every path, including the 143
# endpoints this backend has not ported yet.
#
# Django only uses them when DEBUG is off; with DEBUG on it shows its own
# route-listing page instead, which is the right trade for a developer and the
# reason the test for this pins DEBUG=False.
