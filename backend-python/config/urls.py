"""The routes this backend serves.

Everything hangs under /api/v1/ because that is what the Flutter apps already
call. The prefix is not a style choice; it is part of the contract.

M8 serves auth and students. The other 143 endpoints arrive module by module
from M9, each one landing only when its contract tests pass
(../contract/README.md). Until then this backend answers 404 for them, which
is why it runs alongside Laravel rather than instead of it.

Paths are spelled out one at a time rather than generated by a DRF router.
A router would invent its own URLs - trailing slashes, a `-detail` suffix,
`/students/1/activate/` - and every one of those is a URL the Flutter client
does not call.
"""

from django.urls import path

from school.views import academic_years, auth, imports, schools, students, timezones, users

urlpatterns = [
    # -- academic years ----------------------------------------------------
    path("api/v1/academic-years", academic_years.collection),
    path("api/v1/academic-years/<int:year_id>", academic_years.detail),
    path("api/v1/academic-years/<int:year_id>/set-current", academic_years.set_current),
    # -- auth --------------------------------------------------------------
    path("api/v1/auth/login", auth.login),
    path("api/v1/auth/logout", auth.logout),
    path("api/v1/auth/change-password", auth.change_password),
    path("api/v1/me", auth.me),
    # -- schools -----------------------------------------------------------
    # No DELETE, and not by omission: erasing a school's records is not
    # something a school management system should offer.
    path("api/v1/schools", schools.collection),
    path("api/v1/schools/<int:school_id>", schools.detail),
    path("api/v1/schools/<int:school_id>/activate", schools.activate),
    path("api/v1/schools/<int:school_id>/deactivate", schools.deactivate),
    path("api/v1/timezones", timezones.index),
    # -- users -------------------------------------------------------------
    path("api/v1/users", users.collection),
    path("api/v1/users/<int:user_id>", users.detail),
    path("api/v1/users/<int:user_id>/activate", users.activate),
    path("api/v1/users/<int:user_id>/deactivate", users.deactivate),
    # -- students ----------------------------------------------------------
    path("api/v1/students", students.collection),
    path("api/v1/students/<int:student_id>", students.detail),
    path("api/v1/students/<int:student_id>/activate", students.activate),
    path("api/v1/students/<int:student_id>/deactivate", students.deactivate),
    # -- bulk upload -------------------------------------------------------
    # The kind of record is a path segment, so one pair of endpoints serves
    # every importer. M8 registers `students`; the rest arrive with their
    # modules, and anything else is a 404.
    path("api/v1/imports/<str:kind>", imports.store),
    path("api/v1/imports/<str:kind>/template", imports.template),
]

# A URL matching no route above never reaches DRF, so it would answer Django's
# HTML page - which the Flutter client reads as a parse failure rather than as
# a 404. These keep the error envelope true for every path, including the 143
# endpoints this backend has not ported yet.
#
# Django only uses them when DEBUG is off; with DEBUG on it shows its own
# route-listing page instead, which is the right trade for a developer and the
# reason the test for this pins DEBUG=False.
handler404 = "school.errors.page_not_found"
handler500 = "school.errors.server_error"
